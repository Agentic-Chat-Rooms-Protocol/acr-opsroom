import {
  createEvent,
  Event,
  ExecutionAuthorityLevel,
  WorkflowContent,
} from '../shims.js';
import type { RehydratedNode } from '../utils/rehydration_utils.js';

/**
 * Preserves all node-run checkpoints, predecessor outputs, and elevated
 * execution authority across context compactions so dynamic graphs (`ctx.runNode`)
 * never re-execute completed steps after compaction.
 */
export interface CompactedEventCheckpointManifest {
  invocationId: string;
  paused: boolean;
  runsByPath: Record<string, RehydratedNode[]>;
  outputsByNode: Record<string, unknown>;
  highestAuthority?: ExecutionAuthorityLevel;
}

/**
 * Represents a summary of a sequence of events in a session, extended with
 * deterministic `compactedEventIds` and an optional `checkpointManifest` for
 * checkpoint-safe workflow rehydration.
 */
export interface CompactedEvent extends Event {
  isCompacted: true;
  /** The start time (inclusive) of the compacted events. */
  startTime: number;
  /** The end time (inclusive) of the compacted events. */
  endTime: number;
  /** The summary content generated by the summarizer. */
  compactedContent: WorkflowContent;
  /**
   * Explicit IDs of the events folded into this compaction so same-millisecond
   * events (`e.timestamp === endTime`) are filtered deterministically.
   */
  compactedEventIds?: string[];
  /**
   * Extracted node-run checkpoints and predecessor outputs from compacted events.
   */
  checkpointManifest?: CompactedEventCheckpointManifest;
}

/**
 * Creates a CompactedEvent with default values and a unique ID.
 */
export function createCompactedEvent(
  params: Partial<CompactedEvent> = {}
): CompactedEvent {
  const baseEvent = createEvent(params);
  return {
    ...baseEvent,
    isCompacted: true,
    startTime: params.startTime ?? 0,
    endTime: params.endTime ?? 0,
    compactedContent: params.compactedContent ?? { role: 'model', parts: [] },
    ...(params.compactedEventIds !== undefined
      ? { compactedEventIds: [...params.compactedEventIds] }
      : {}),
    ...(params.checkpointManifest !== undefined
      ? { checkpointManifest: params.checkpointManifest }
      : {}),
  };
}

/**
 * Type guard to check if an Event is a CompactedEvent.
 */
export function isCompactedEvent(event: Event): event is CompactedEvent {
  return (event as CompactedEvent)?.isCompacted === true;
}

/**
 * Checks if an event is a scratchpad event (part of an isolated scope).
 */
export function isScratchpadEvent(event: Event): boolean {
  return event?.isolationScope !== undefined;
}
